#!/usr/bin/env python3
"""ESP Serial2WiFi SDK 3 flash geometry; all ranges are half-open bytes."""
import argparse
import binascii
import json
import struct
from pathlib import Path

TARGETS = {"512KB": (0, 0x80000), "1MB": (2, 0x100000),
           "2MB": (3, 0x200000), "4MB": (4, 0x400000)}


def layout(target, external_ui=False):
    map_id, size = TARGETS[target]
    small = target == "512KB"
    regions = {
        "boot": (0, 0x1000),
        "app1": (0x1000, 0x75000 if small else 0x7b000),
        "config": (0x7a000 if small else 0x7e000, 0x2000),
        "rf": (0x76000 if small else 0x80000, 0x1000),
        "phy": (size - 0x4000, 0x1000),
        "params": (size - 0x3000, 0x3000),
    }
    if not small:
        regions["app2"] = (0x81000, 0x7b000)
    pages = (0x79000, 0x1000) if small else ((0x7c000, 0x2000)
             if target == "1MB" else (0x100000, size - 0x104000))
    if external_ui:
        if target != "4MB":raise ValueError("External UI requires the 4MB layout")
        regions["ui1"] = (0x37c000, 0x40000)
        regions["ui2"] = (0x3bc000, 0x40000)
        pages = (pages[0], regions["ui1"][0] - pages[0])
    regions["pages"] = pages
    result = {"target": target, "map": map_id, "bytes": size,
              "ota_geometry": not small, "regions": regions,
              "image_abi": f"ELSDK306-MAP{map_id}-CFG{2 if external_ui else 1}"}
    validate(result)
    return result


def validate(value):
    spans = []
    for name, (start, size) in value["regions"].items():
        if start < 0 or size <= 0 or start % 4096 or size % 4096:
            raise ValueError(f"unaligned/empty region: {name}")
        if start + size > value["bytes"]:
            raise ValueError(f"out-of-range region: {name}")
        spans.append((start, start + size, name))
    spans.sort()
    for left, right in zip(spans, spans[1:]):
        if left[1] > right[0]:
            raise ValueError(f"overlap: {left[2]} and {right[2]}")
    if value["regions"]["app1"][0] != 0x1000:
        raise ValueError("SDK app1 address is fixed")
    if "app2" in value["regions"] and value["regions"]["app2"][0] != 0x81000:
        raise ValueError("SDK 512+512 app2 address is fixed")


def header(value):
    lines = ["/* Generated by tools/lib/flash_layout.py; do not edit. */",
             "#ifndef GENERATED_FLASH_LAYOUT_H", "#define GENERATED_FLASH_LAYOUT_H",
             f'#define FLASH_LAYOUT_MAP {value["map"]}',
             f'#define FLASH_LAYOUT_BYTES 0x{value["bytes"]:x}U',
             f'#define FLASH_LAYOUT_OTA_CAPABLE {int(value["ota_geometry"])}',
             f'#define SERIAL2WIFI_IMAGE_ABI "{value["image_abi"]}"']
    lines.append(f"#define FLASH_EXTERNAL_UI {int('ui1' in value['regions'])}")
    for name in ("boot", "app1", "app2", "config", "pages", "ui1", "ui2", "rf", "phy", "params"):
        start, size = value["regions"].get(name, (0, 0))
        lines += [f"#define FLASH_{name.upper()}_START 0x{start:x}U",
                  f"#define FLASH_{name.upper()}_SIZE 0x{size:x}U"]
    return "\n".join(lines + ["#endif", ""])


def check_image(image, value, slot):
    return check_image_data(image.read_bytes(), value, slot, str(image))

def check_image_data(data, value, slot, image="application"):
    region = value['regions'].get('app' + str(slot + 1))
    if region is None or len(data) > region[1] or len(data) < 1024 or len(data) % 16 != 4:
        raise ValueError(f'{image}: image size/slot is unsupported')
    if data[:4] != bytes((0xea, 4, 0, slot)):
        raise ValueError(f'{image}: invalid application header or slot')
    inner = 16 + struct.unpack_from('<I', data, 12)[0]
    if (inner > len(data) - 12 or data[inner:inner+2] != b'\xe9\x03' or
            data[inner+3] >> 4 != value['map'] or data[inner+2] > 3 or
            data[inner+3] & 15 not in (0, 1, 2, 15)):
        raise ValueError(f'{image}: embedded flash map does not match target')
    if value['image_abi'].encode() not in data:
        raise ValueError(f'{image}: missing SDK/layout identity')
    crc = binascii.crc32(data[:-4])
    expected = ~crc & 0xffffffff if crc & 0x80000000 else crc + 1
    if struct.unpack_from('<I', data, len(data)-4)[0] != expected:
        raise ValueError(f'{image}: invalid image footer CRC')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", choices=TARGETS)
    parser.add_argument("--external-ui", action="store_true")
    parser.add_argument("--header", type=Path)
    parser.add_argument("--image", action="append", type=Path, default=[])
    args = parser.parse_args()
    value = layout(args.target, args.external_ui)
    for image in args.image:
        try:
            check_image(image, value, 1 if image.name == 'user2.bin' else 0)
        except ValueError as error:
            parser.error(str(error))
    if args.header:
        content = header(value)
        args.header.parent.mkdir(parents=True, exist_ok=True)
        if not args.header.exists() or args.header.read_text() != content:
            args.header.write_text(content)
    else:
        print(json.dumps(value, indent=2))


if __name__ == "__main__":
    main()
